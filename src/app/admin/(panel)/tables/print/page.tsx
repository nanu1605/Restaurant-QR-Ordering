import { ArrowLeft, QrCode } from 'lucide-react';
import type { Metadata } from 'next';
import Link from 'next/link';

import { EmptyState } from '@/components/shared/empty-state';
import { PageHeader } from '@/components/shared/page-header';
import { buttonVariants } from '@/components/ui/button';
import { isLocalAppUrl, qrSvg, tableUrl } from '@/features/tables/qr';
import { getAdminTables } from '@/features/tables/queries';
import { requireMember } from '@/lib/auth/guards';
import { ADMIN_PANEL_ROLES } from '@/lib/auth/roles';
import { getPublicEnv } from '@/lib/env';

import { PrintButton } from './print-button';

export const metadata: Metadata = {
  title: 'Print QR cards',
};

const CARDS_PER_PAGE = 6;

/**
 * Printable A4 sheet of table cards, 6 per page (spec §13.3, §15): restaurant
 * name, "Scan to order", the table label, its QR code and "No app needed".
 * ?tables=<id>,<id> prints just those tables; otherwise every active table.
 */
export default async function PrintQrCardsPage({ searchParams }: PageProps<'/admin/tables/print'>) {
  const membership = await requireMember(ADMIN_PANEL_ROLES);
  const { tables: selection } = await searchParams;
  const selectedIds = typeof selection === 'string' ? selection.split(',').filter(Boolean) : [];

  const appUrl = getPublicEnv().NEXT_PUBLIC_APP_URL;
  const tables = (await getAdminTables()).filter(
    (table) => table.isActive && (selectedIds.length === 0 || selectedIds.includes(table.id)),
  );
  const cards = await Promise.all(
    tables.map(async (table) => ({
      id: table.id,
      label: table.label,
      svg: await qrSvg(tableUrl(appUrl, table.qrToken)),
    })),
  );
  const pages = Array.from({ length: Math.ceil(cards.length / CARDS_PER_PAGE) }, (_, index) =>
    cards.slice(index * CARDS_PER_PAGE, (index + 1) * CARDS_PER_PAGE),
  );

  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-col gap-3 print:hidden">
        <PageHeader
          title="Print QR cards"
          description={`${cards.length} ${cards.length === 1 ? 'card' : 'cards'}, ${CARDS_PER_PAGE} per A4 page. In the print dialog choose A4 and turn off headers and footers.`}
          actions={
            <>
              <Link
                href="/admin/tables"
                className={buttonVariants({ variant: 'outline', size: 'lg' })}
              >
                <ArrowLeft aria-hidden /> Tables
              </Link>
              <PrintButton disabled={cards.length === 0} />
            </>
          }
        />
        {isLocalAppUrl(appUrl) && (
          <p
            role="note"
            className="rounded-md border-l-4 border-status-preparing bg-surface px-3 py-2 text-sm text-ink"
          >
            These codes open {appUrl}, which only works on this network. Set the app&apos;s web
            address (NEXT_PUBLIC_APP_URL) to your real domain before printing cards for customers.
          </p>
        )}
      </div>

      {cards.length === 0 ? (
        <EmptyState
          icon={QrCode}
          title="No tables to print"
          description="Add tables first, then print their QR cards here."
        />
      ) : (
        <div className="flex flex-col items-center gap-6 print:block">
          {pages.map((page, index) => (
            <section
              key={index}
              aria-label={`Page ${index + 1}`}
              className="qr-page grid w-full max-w-[210mm] grid-cols-2 grid-rows-3 gap-[6mm] border border-line bg-white p-[10mm] shadow-sm print:max-w-none print:border-0 print:p-0 print:shadow-none"
            >
              {page.map((card) => (
                <article
                  key={card.id}
                  aria-label={`Table ${card.label}`}
                  className="flex h-[82mm] break-inside-avoid flex-col items-center justify-between rounded-xl border-2 border-dashed border-line px-[5mm] py-[4mm] text-center"
                >
                  <p className="line-clamp-1 text-sm font-semibold text-ink-muted">
                    {membership.restaurant.name}
                  </p>
                  <p className="text-lg font-bold text-ink">Scan to order</p>
                  <div
                    className="size-[40mm] [&>svg]:size-full"
                    role="img"
                    aria-label={`QR code for table ${card.label}`}
                    // SVG generated by the qrcode library from our own URL.
                    dangerouslySetInnerHTML={{ __html: card.svg }}
                  />
                  <div className="flex flex-col items-center leading-none">
                    <span className="text-xs text-ink-muted">Table</span>
                    <span className="text-[2rem] font-bold text-ink">{card.label}</span>
                  </div>
                  <p className="text-xs text-ink-muted">No app needed</p>
                </article>
              ))}
            </section>
          ))}
        </div>
      )}
    </div>
  );
}
